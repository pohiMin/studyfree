total = 0
for un, pgs in UNIT_PAGES.items():
    path = os.path.join(BASE, "content", "u{}.py".format(un))
    if not os.path.exists(path):
        continue
    spec = importlib.util.spec_from_file_location("u{}".format(un), path)
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    U = m.UNIT

    vids = []
    for p in pgs:
        t, kws = META[p]
        vids.append({
            "title": t,
            "keywords": kws,
            "source": "B站 · 国家中小学课程资源",
            "ep": "第 {} 集".format(p),
            "duration": dur(p),
            "kind": "official",
            "tag": "同步课",
            "url": URL_TPL.format(BV, p),
        })
    U["videos"] = vids

    head = "# {}\n# 内容源：直接修改本文件后重新运行 build.py 即可\n\nUNIT = ".format(
        "第{}单元 · {}".format(un, U["unitTitle"]) if un <= 8 else "期末复习")
    s = head + pprint.pformat(U, width=150, sort_dicts=False) + "\n"
    io.open(path, "w", encoding="utf-8").write(s)
    total += len(vids)
    print(f"  U{un}：{len(vids)} 个视频")

print("合计推荐视频：", total)
